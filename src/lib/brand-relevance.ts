/**
 * متى تُستخدم بيانات العلامة؟ العلامة مرجع اختياري: تُذكر حين يكون الطلب عن النشاط
 * أو يطلبها المالك، وتُسقط تماماً حين يطلب تجاهلها أو يكون الموضوع عاماً.
 */
const OPT_OUT =
  /(انس[يىا]|تجاهل|بدون|من\s*غير|مش\s*عايز|ماتذكرش|متذكرش|لا\s*تذكر|ماتجيبش|متجيبش|شيل)\s*(اسم\s*)?(ال)?(علامة|براند|شرك[ةه]|منص[ةه]|موقع|megsy|ميجسي)?/i;
const OPT_IN = /(ارجع|رجّع|رجع)\s*(لل|ل)?(علامة|براند|شرك[ةه])|عن\s*(شركتي|منصتي|موقعي|براندي|علامتي)|روّج|روج|اعلان|إعلان|عرض\s*(خصم|سعر)/i;

/** يفحص رسائل المستخدم من الأحدث للأقدم: أحدث تفضيل صريح يحسم. */
export function brandOptedOut(userMessagesNewestFirst: string[], brandName?: string | null): boolean {
  const name = (brandName ?? "").trim().toLowerCase();
  for (const raw of userMessagesNewestFirst) {
    const m = raw.toLowerCase();
    if (OPT_IN.test(m)) return false;
    const mentionsBrand = name && m.includes(name);
    if (OPT_OUT.test(m) && (mentionsBrand || /(علامة|براند|شرك|منص|موقع|megsy|ميجسي)/i.test(m))) return true;
    if (/انس[يىا]/.test(m) && mentionsBrand) return true;
  }
  return false;
}

export function brandUsageRule(brandName: string | null | undefined, optedOut: boolean): string {
  if (optedOut) {
    return "## العلامة موقوفة في هذه المحادثة\nالمالك طلب صراحة تجاهل العلامة: لا تذكر اسمها ولا رابطها ولا منتجاتها ولا هاشتاجها إطلاقاً، واكتب عن الموضوع المطلوب وحده، حتى يطلب الرجوع إليها.";
  }
  return `## متى تذكر العلامة\nبيانات العلامة${brandName ? ` «${brandName}»` : ""} مرجع اختياري لا إلزامي: اذكر الاسم والرابط والمنتجات فقط حين يكون الطلب ترويجياً أو عن النشاط أو يطلبها المالك. في المواضيع العامة (مشاعر، مناسبات، نصائح، معلومات) اكتب عن الموضوع نفسه بصوت العلامة فقط، بلا اسمها ولا رابطها ولا هاشتاجها.`;
}

